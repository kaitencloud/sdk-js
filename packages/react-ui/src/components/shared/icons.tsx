type IconProps = React.SVGProps<SVGSVGElement>;

// Hidden from assistive tech by default. These glyphs are decorative nearly
// everywhere they appear — beside a feature name, inside a card title — and an
// unlabelled <svg> contributes an empty accessible name either way. Defaulting
// to hidden makes the exception explicit: a caller that uses an icon AS the
// content has to name it, rather than silently shipping a cell that reads the
// same whether the feature is included or not. `{...props}` still wins, so
// `aria-hidden={false}` remains available.
